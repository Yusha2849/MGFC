const POSITIONS_CYCLE: Player['position'][] = ['GK', 'DF', 'MF', 'FW', 'DF', 'MF', 'FW', 'DF', 'MF', 'FW', 'MF', 'DF', 'FW', 'MF'];

export function buildPlayersFromFeeSheets(sheets: TeamFeeSheet[]): Player[] {
  const result: Player[] = [];
  sheets.forEach(sheet => {
    const birthYear = AGE_BIRTH_YEARS[sheet.id] || 2016;
    sheet.players.forEach((row, idx) => {
      if (row.isDonationRow) return;
      const position = POSITIONS_CYCLE[idx % POSITIONS_CYCLE.length];
      const feeStatus: Player['feeStatus'] =
        row.amountDue === 0
          ? 'Exempt / Bursary'
          : row.balanceDue <= 0
          ? 'Paid'
          : row.totalPaid > 0
          ? 'Partial'
          : 'Overdue';
      const monthStr = String(((idx % 12) + 1)).padStart(2, '0');
      const dayStr = String(((idx * 3 + 5) % 28) + 1).padStart(2, '0');
      const fullSlug = `${row.name}.${row.surname || sheet.id}`.toLowerCase().replace(/[^a-z0-9.]/g, '');

      result.push({
        id: row.id,
        firstName: row.name,
        lastName: row.surname || '—',
        squadId: sheet.id,
        position,
        jerseyNumber: row.no,
        dob: `${birthYear}-${monthStr}-${dayStr}`,
        idNumber: `${String(birthYear).slice(-2)}${monthStr}${dayStr}500008${idx % 10}`,
        safaNumber: row.cardNumber || 'Pending Card',
        status: row.isInactive ? 'Inactive' : 'Active',
        phone: `+27 82 ${String(300 + idx * 17).slice(0, 3)} ${String(1000 + row.no * 111).slice(0, 4)}`,
        email: `${fullSlug}@mgfc.co.za`,
        parentGuardian: row.surname ? `Parent (${row.surname})` : 'Parent / Guardian',
        parentPhone: `+27 83 ${String(400 + idx * 19).slice(0, 3)} ${String(2000 + row.no * 123).slice(0, 4)}`,
        medicalNotes: row.remarks || 'No known allergies or chronic conditions.',
        feeDue: row.amountDue,
        feePaid: row.totalPaid,
        feeStatus,
        appearances: row.isInactive ? 2 : 8 + (idx % 4),
        goals: position === 'GK' ? 0 : (idx % 5),
        assists: position === 'GK' ? 0 : ((idx + 1) % 4),
        yellowCards: idx % 3 === 0 ? 1 : 0,
        redCards: 0,
        attendanceRate: row.isInactive ? 35 : 88 + (idx % 12),
        dateJoined: '2026-02-01',
      });
    });
  });
  return result;
}

